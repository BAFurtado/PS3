def main():
    print("=" * 90)
    print("TIER-2 COMPARISON: corrected model, 26 of 27 cities (SAO PAULO pending)")
    print("=" * 90)

    print("\n[0] Batch integrity")
    new = load_stats(NEW_STATS, "new")
    old = load_stats(OLD_STATS, "submitted")
    cities26 = sorted(new["processing_acps"].unique())
    old26 = old[old["processing_acps"].isin(cities26)].copy()
    for lab, d in [("new", new), ("submitted", old)]:
        cells = d.groupby(["processing_acps", "policy_melhorias",
                           "interest_housing"])["seed"].nunique()
        print(f"  [{lab}] sims={d['simulation_id'].nunique()} "
              f"cities={d['processing_acps'].nunique()} "
              f"seeds/cell={sorted(cells.unique())} "
              f"cells={len(cells)}")
    missing = sorted(set(old["processing_acps"].unique()) - set(cities26))
    print(f"  cities in submitted but not in new: {missing}")

    # matched-seed check: the three interest arms share historical rates pre-2020
    pre = new[new["month"] < "2020-01-01"]
    cols = ["gdp_level", "unemployment", "house_price", "house_vacancy",
            "gini_index", "pop"]
    worst = 0.0
    for _, g in pre.groupby(["processing_acps", "policy_melhorias", "seed"]):
        piv = g.pivot_table(index="month", columns="interest_housing", values=cols)
        for c in cols:
            s = piv[c]
            den = s.abs().max(axis=1).replace(0, np.nan)
            worst = max(worst, float(((s.max(axis=1) - s.min(axis=1)).abs() / den).max()))
    print(f"  [new] max pre-2020 relative spread across interest arms: {worst:.2e} -> "
          f"{'MATCHED' if worst < 1e-9 else 'NOT MATCHED'}")

    reg_new = load_regional(NEW_REG, "new")
    print(f"  [new] regional rows={len(reg_new):,} sims={reg_new['simulation_id'].nunique()} "
          f"munis={reg_new['mun_id'].nunique()}")

    # ---- 1. levels ------------------------------------------------------
    print(f"\n[1] Nine validation indicators, eval window {EVAL_START[:7]}..{EVAL_END[:7]}")
    p_new, city_new = validation_levels(new)
    p_old26, city_old = validation_levels(old26)
    p_old27, _ = validation_levels(old)
    lv = pd.DataFrame({"submitted27": p_old27, "submitted26": p_old26, "new26": p_new})
    lv["pct_chg_vs_sub26"] = 100 * (lv["new26"] - lv["submitted26"]) / lv["submitted26"].abs()
    lv["target"] = [f"{TARGETS[i][0]:g}-{TARGETS[i][1]:g}" for i in lv.index]
    v = lambda i, x: "PASS" if TARGETS[i][0] <= x <= TARGETS[i][1] else "FAIL"
    lv["v_sub27"] = [v(i, x) for i, x in lv["submitted27"].items()]
    lv["v_sub26"] = [v(i, x) for i, x in lv["submitted26"].items()]
    lv["v_new26"] = [v(i, x) for i, x in lv["new26"].items()]
    lv["verdict_change"] = np.where(lv["v_sub26"] == lv["v_new26"], "", "<-- CHANGED")
    print(lv.round(4).to_string())
    lv.to_csv(OUT_DIR / "density_tier2_levels.csv")

    per_city = (city_new - city_old) / city_old.abs() * 100
    print("\n  per-city % change vs submitted (same city):")
    print(per_city.round(1).to_string())
    per_city.to_csv(OUT_DIR / "density_tier2_levels_by_city.csv")

    print("\n[1b] Paper Table 2 (housing validation), published format")
    t_old27, t_old26, t_new = paper_table2(old), paper_table2(old26), paper_table2(new)
    fmt = lambda t, i: f"{t.loc[i,'median']:.3g} ({t.loc[i,'p10']:.3g}-{t.loc[i,'p90']:.3g})"
    inside = lambda x, i: PAPER_TABLE2[i][0] <= x <= PAPER_TABLE2[i][1]
    t2 = pd.DataFrame({
        "empirical": [f"{PAPER_TABLE2[i][0]:g}-{PAPER_TABLE2[i][1]:g}" for i in PAPER_TABLE2],
        "submitted27": [fmt(t_old27, i) for i in PAPER_TABLE2],
        "submitted26": [fmt(t_old26, i) for i in PAPER_TABLE2],
        "new26": [fmt(t_new, i) for i in PAPER_TABLE2],
        "pct_chg": [100 * (t_new.loc[i, "median"] - t_old26.loc[i, "median"])
                    / abs(t_old26.loc[i, "median"]) for i in PAPER_TABLE2],
        "dag_pub": ["" if inside(t_old27.loc[i, "median"], i) else "dag" for i in PAPER_TABLE2],
        "dag_new": ["" if inside(t_new.loc[i, "median"], i) else "dag" for i in PAPER_TABLE2],
    }, index=list(PAPER_TABLE2))
    t2["changed"] = np.where(t2.dag_pub != t2.dag_new, "<-- FLIP", "")
    print(t2.round(3).to_string())
    t2.to_csv(OUT_DIR / "density_tier2_paper_table2.csv")

    # ---- 2. delta panels -------------------------------------------------
    print("\n[2] Building delta panels (prepare_data.py logic) for the new batch")
    acp_n, cap_n, per_n, (t0, t1) = build_panels(new, reg_new)
    expect = 5 * new.groupby("processing_acps")["seed"].nunique().sum()
    print(f"  window {t0:%Y-%m}..{t1:%Y-%m}   acp={len(acp_n)} (expect {expect}) "
          f"cap={len(cap_n)} per={len(per_n)} rows; "
          f"periphery cities={per_n['processing_acps'].nunique()}")
    assert len(acp_n) == expect, "delta panel row count != cities x 5 configs x seeds"
    acp_p27, cap_p27, per_p27 = load_published_panels()
    acp_p26, cap_p26, per_p26 = load_published_panels(cities26)
    print(f"  published: acp27={len(acp_p27)} acp26={len(acp_p26)} "
          f"per27={len(per_p27)} per26={len(per_p26)}")
    acp_n.to_csv(OUT_DIR / "density_tier2_acp_deltas.csv", index=False)
    cap_n.to_csv(OUT_DIR / "density_tier2_capital_deltas.csv", index=False)
    per_n.to_csv(OUT_DIR / "density_tier2_periphery_deltas.csv", index=False)

    # ---- 3. Table 3 ------------------------------------------------------
    print("\n[3] Eq. 3 at three levels (OLS + city FE, HC3) -- the paper's Table 3")
    rows = []
    rows += table3((acp_p27, cap_p27, per_p27), "published n=3 (27 cities)")
    rows += table3((acp_p26, cap_p26, per_p26), "published n=3 (26 cities)")
    rows += table3((acp_n, cap_n, per_n), "new n=10 (26 cities)")
    sub3 = lambda d: d[d["seed"] < 3]
    rows += table3((sub3(acp_n), sub3(cap_n), sub3(per_n)), "new n=3 subsample (26)")
    reg = pd.DataFrame(rows)
    for mech in ["secondary (rent/income)", "primary (house price)"]:
        print(f"\n  === mechanism: {mech} ===")
        for sname in ["all configs", "melhorias OFF", "melhorias ON"]:
            s = reg[(reg["mechanism"] == mech) & (reg["subset"] == sname)]
            print(f"\n  -- {sname}")
            print(s[["level", "batch", "beta", "se", "t", "p", "stars", "r2", "n"]]
                  .to_string(index=False,
                             formatters={"beta": "{:+.4g}".format, "se": "{:.3g}".format,
                                         "t": "{:+.2f}".format, "p": "{:.3g}".format,
                                         "r2": "{:.3f}".format}))
    reg.to_csv(OUT_DIR / "density_tier2_regressions.csv", index=False)

    # ---- 4. slope heterogeneity -----------------------------------------
    print("\n[4] Is Eq. 3's common-slope restriction defensible? "
          "(secondary mechanism, ACP level)")
    slope_rows, het_rows = [], []
    for tag, d in [("published n=3 (27)", acp_p27), ("published n=3 (26)", acp_p26),
                   ("new n=10 (26)", acp_n)]:
        for arm, s in [("OFF", d[~d["policy_melhorias"]]), ("ON", d[d["policy_melhorias"]])]:
            y, _, mech = SPECS["ACP"]
            pooled = eq3(s, y, mech, cov="nonrobust")
            cl = clustered(s, y, mech)
            pool = poolability(s, y, mech)
            cs = city_slopes(s, y, mech)
            mg = mean_group(cs)
            print(f"\n  {tag} | melhorias {arm}")
            print(f"    pooled FE beta = {pooled['beta']:+.4f} (p={pooled['p']:.3g}"
                  f"{pooled['stars']}) | city-clustered p={cl['p']:.3g}")
            print(f"    mean-group     = {mg['mean_group']:+.4f} "
                  f"(se={mg['se']:.3f}, p={mg['p']:.3g}, k={mg['k_cities']})")
            print(f"    common-slope F({pool['df_num']:.0f},{pool['df_den']:.0f})="
                  f"{pool['F']:.2f} p={pool['p']:.3g} -> "
                  f"{'REJECTED' if pool['p'] < 0.05 else 'not rejected'}")
            top = cs.head(6)
            print(f"    top-6 FE weights: " + ", ".join(
                f"{r.city} b={r.beta:+.2f} w={r.weight:.2f}" for r in top.itertuples()))
            print(f"    weight concentration: top-3 = {cs['weight'].head(3).sum():.0%}, "
                  f"share of cities with beta>0 = {(cs['beta'] > 0).mean():.0%}")
            cs.insert(0, "arm", arm)
            cs.insert(0, "batch", tag)
            slope_rows.append(cs)
            het_rows.append({"batch": tag, "arm": arm, "pooled_fe": pooled["beta"],
                             "pooled_p": pooled["p"], "cluster_p": cl["p"],
                             "mean_group": mg["mean_group"], "mg_se": mg["se"],
                             "mg_p": mg["p"], "F": pool["F"], "F_p": pool["p"],
                             "k_cities": mg["k_cities"],
                             "top3_weight": cs["weight"].head(3).sum(),
                             "share_beta_pos": (cs["beta"] > 0).mean()})
    pd.concat(slope_rows).to_csv(OUT_DIR / "density_tier2_city_slopes.csv", index=False)

    # ---- 4b. did the coefficients actually move? -------------------------
    # Two independent estimates (no matched seeds exist -- defect #6), so a
    # Wald z on the difference is the available test.
    def zdiff(a, b):
        d = a["beta"] - b["beta"]
        se = np.hypot(a["se"], b["se"])
        z = d / se
        return d, se, z, 2 * (1 - sps.norm.cdf(abs(z)))

    print("\n[4b] Wald z-tests: (i) published vs corrected, (ii) the paper's own "
          "1.16-vs-0.66 lever comparison, within each batch")
    cmp_rows = []
    for level in ["ACP", "Capital", "Periphery"]:
        for mech in ["secondary (rent/income)", "primary (house price)"]:
            for sname in ["melhorias OFF", "melhorias ON", "all configs"]:
                sel = lambda b: reg[(reg.level == level) & (reg.mechanism == mech)
                                    & (reg.subset == sname) & (reg.batch == b)]
                a, b = sel("published n=3 (26 cities)"), sel("new n=10 (26 cities)")
                if a.empty or b.empty:
                    continue
                d, se, z, p = zdiff(a.iloc[0], b.iloc[0])
                cmp_rows.append({"test": "published26 vs new26", "level": level,
                                 "mechanism": mech, "subset": sname,
                                 "beta_pub": a.iloc[0]["beta"], "beta_new": b.iloc[0]["beta"],
                                 "diff": d, "z": z, "p": p})
    for batch in ["published n=3 (26 cities)", "new n=10 (26 cities)"]:
        for level in ["ACP", "Capital", "Periphery"]:
            sel = lambda s: reg[(reg.level == level)
                                & (reg.mechanism == "secondary (rent/income)")
                                & (reg.subset == s) & (reg.batch == batch)]
            off, on = sel("melhorias OFF"), sel("melhorias ON")
            if off.empty or on.empty:
                continue
            d, se, z, p = zdiff(off.iloc[0], on.iloc[0])
            cmp_rows.append({"test": f"OFF vs ON within {batch}", "level": level,
                             "mechanism": "secondary (rent/income)", "subset": "OFF - ON",
                             "beta_pub": off.iloc[0]["beta"], "beta_new": on.iloc[0]["beta"],
                             "diff": d, "z": z, "p": p})
    cmpdf = pd.DataFrame(cmp_rows)
    print(cmpdf.to_string(index=False, formatters={
        "beta_pub": "{:+.4g}".format, "beta_new": "{:+.4g}".format,
        "diff": "{:+.4g}".format, "z": "{:+.2f}".format, "p": "{:.3g}".format}))
    cmpdf.to_csv(OUT_DIR / "density_tier2_coef_tests.csv", index=False)
    het = pd.DataFrame(het_rows)
    print("\n  summary")
    print(het.to_string(index=False, float_format=lambda x: f"{x:.4g}"))
    het.to_csv(OUT_DIR / "density_tier2_heterogeneity.csv", index=False)

    # ---- 5. delta magnitudes by config ----------------------------------
    print("\n[5] Delta magnitudes by configuration (ACP level, mean +/- sd over cities x seeds)")
    for tag, d in [("published n=3 (26)", acp_p26), ("new n=10 (26)", acp_n)]:
        g = (d.groupby("policy_config")[["delta_gini", "delta_affordability_median",
                                         "delta_house_price", "delta_house_quality"]]
               .agg(["mean", "std"]))
        print(f"\n  {tag}")
        print(g.round(6).to_string())

    # ---- 6. capital vs periphery ----------------------------------------
    print("\n[6] Capital vs periphery gap (periphery - capital), the paper's Section 3.5")
    gaps = []
    for tag, cp, pp in [("published n=3 (26)", cap_p26, per_p26),
                        ("new n=10 (26)", cap_n, per_n)]:
        c = cp[["processing_acps", "policy_config", "seed", "delta_regional_gini",
                "delta_regional_house_values", "delta_median_affordability"]]
        p = pp[["processing_acps", "policy_config", "seed", "delta_gini_periphery",
                "delta_house_values_periphery", "delta_median_affordability_periphery"]]
        pr = c.merge(p, on=["processing_acps", "policy_config", "seed"], how="inner")
        pr["gap_gini"] = pr["delta_gini_periphery"] - pr["delta_regional_gini"]
        pr["gap_rent"] = (pr["delta_median_affordability_periphery"]
                          - pr["delta_median_affordability"])
        cty = pr.groupby("processing_acps")[["delta_regional_gini", "delta_gini_periphery",
                                             "gap_gini", "gap_rent"]].mean()
        n_worse = int((cty["gap_gini"] > 0).sum())
        t = sps.ttest_1samp(cty["gap_gini"], 0)
        print(f"\n  {tag}: periphery worse in {n_worse}/{len(cty)} cities; "
              f"mean gap={cty['gap_gini'].mean():+.6f} (paired t p={t.pvalue:.3g})")
        cty.insert(0, "batch", tag)
        gaps.append(cty)
    pd.concat(gaps).to_csv(OUT_DIR / "density_tier2_capital_periphery.csv")

    # ---- 7. melhorias take-up -------------------------------------------
    print("\n[7] Melhorias take-up, with the eligible base beside it "
          "(no melhorias number travels without its base)")
    on = reg_new[reg_new["policy_melhorias"]]
    # Eligible base at the moment the policy can first act, summed over the
    # ACP's municipalities; upgrades cumulated over the whole 30-year horizon.
    start = on["month"].min()
    base = (on[on["month"] == start].groupby(["processing_acps", "simulation_id"])
              .agg(eligible0=("melhorias_eligible", "sum"), pop0=("pop", "sum"))
              .reset_index().groupby("processing_acps")[["eligible0", "pop0"]].mean())
    tot = (on.groupby(["processing_acps", "simulation_id"])["melhorias_upgrades"].sum()
             .reset_index().groupby("processing_acps")["melhorias_upgrades"]
             .agg(["mean", "std"]))
    tk = base.join(tot.rename(columns={"mean": "upgrades_total",
                                       "std": "upgrades_sd"}))
    tk["eligible0_per_1000"] = 1000 * tk["eligible0"] / tk["pop0"]
    # 30-year flow of upgrades against the t=0 eligible stock, so ratios above
    # 100% are expected: the eligible stock replenishes as houses degrade and
    # new families form.
    tk["upgrades_per_base0"] = tk["upgrades_total"] / tk["eligible0"].replace(0, np.nan)
    tk = tk.sort_values("eligible0_per_1000", ascending=False)
    print(tk[["eligible0", "pop0", "eligible0_per_1000", "upgrades_total",
              "upgrades_sd", "upgrades_per_base0"]]
          .to_string(float_format=lambda x: f"{x:.2f}"))
    print(f"  cities where melhorias never fires: "
          f"{sorted(tk.index[tk['upgrades_total'] == 0])}")
    tk.to_csv(OUT_DIR / "density_tier2_melhorias_takeup.csv")

    # ---- 8. cross-city ordering resolvability ---------------------------
    print("\n[8] Is the per-city ordering resolvable at n=10? "
          "(mean delta_gini per city, +/- sem across configs x seeds)")
    ord_rows = []
    for tag, d in [("published n=3 (26)", acp_p26), ("new n=10 (26)", acp_n)]:
        g = d.groupby("processing_acps")["delta_gini"].agg(["mean", "sem", "count"])
        g["t"] = g["mean"] / g["sem"]
        g["sig05"] = g["t"].abs() > 1.96
        print(f"\n  {tag}: {int(g['sig05'].sum())}/{len(g)} cities with "
              f"|t|>1.96 on mean delta_gini")
        g.insert(0, "batch", tag)
        ord_rows.append(g)
    ordf = pd.concat(ord_rows)
    ordf.to_csv(OUT_DIR / "density_tier2_city_ordering.csv")
    piv = ordf.reset_index().pivot(index="processing_acps", columns="batch", values="mean")
    if piv.shape[1] == 2:
        rho = piv.corr(method="spearman").iloc[0, 1]
        pr = piv.corr().iloc[0, 1]
        print(f"\n  rank correlation of per-city mean delta_gini, published vs new: "
              f"spearman={rho:+.3f}  pearson={pr:+.3f}")
        print(piv.sort_values(piv.columns[0]).round(6).to_string())

    print(f"\nWrote density_tier2_*.csv to {OUT_DIR}")



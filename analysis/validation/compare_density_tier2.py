"""Comparison for the `text_density` re-run: all 27 of the paper's cities.

Inputs
------
new batch (corrected model, 6 configs/city):
    output/final_stats_27cities.csv     + output/regional_stats_27cities.csv
    -> 26 cities x 6 configs x 10 seeds, plus SAO PAULO x 6 configs x 6 seeds
       = 1596 sims.

submitted batch (the published paper, n=3):
    output/old/final_stats_agglomeration_submitted.csv          (raw, for levels)
    private/overleaf/text_density/data_submitted/{acp,capital,periphery}_deltas.csv  (the published
    delta panels themselves -- used verbatim so the "submitted" column is the
    paper's own numbers, not a re-derivation of them).

The delta panels for the new batch are built with the *same* code path as
`papers/density_housing_inequality/prepare_data.py` (60-month tail window, baseline =
melhorias OFF x interest medium, matched on city+seed, periphery
population-weighted on baseline pop), and the regressions are the same specs
as `papers/density_housing_inequality/regression.py` (OLS + city FE, HC3).

Every table is reported both on the full published city set and on the subset
the new batch covers, so that a change in coverage is never confused with a
change in the model; plus a 3-seed subsample of the new batch, which isolates
"the design changed from n=3" from "the model changed".

Usage:
    python analysis/validation/compare_density_tier2.py
"""

def eq3(df, outcome, mech, cov="HC3"):
    fit = smf.ols(f"{outcome} ~ {mech} + C(processing_acps)", data=df).fit(cov_type=cov)
    p = fit.pvalues[mech]
    return {"beta": fit.params[mech], "se": fit.bse[mech], "t": fit.tvalues[mech],
            "p": p, "stars": stars(p), "r2": fit.rsquared, "n": int(fit.nobs),
            "n_cities": df["processing_acps"].nunique()}


SPECS = {
    "ACP": ("delta_gini", "delta_house_price", "delta_affordability_median"),
    "Capital": ("delta_regional_gini", "delta_regional_house_values",
                "delta_median_affordability"),
    "Periphery": ("delta_gini_periphery", "delta_house_values_periphery",
                  "delta_median_affordability_periphery"),
}


def table3(panels, tag):
    """Every cell of the paper's Table 3 / regression_split, for one batch."""
    acp, cap, per = panels
    rows = []
    for level, df in [("ACP", acp), ("Capital", cap), ("Periphery", per)]:
        y, m_prim, m_sec = SPECS[level]
        subsets = [("all configs", df),
                   ("melhorias OFF", df[~df["policy_melhorias"]]),
                   ("melhorias ON", df[df["policy_melhorias"]])]
        for sname, sub in subsets:
            if len(sub) < 10:
                continue
            for mname, mech in [("primary (house price)", m_prim),
                                ("secondary (rent/income)", m_sec)]:
                r = eq3(sub, y, mech)
                r.update({"batch": tag, "level": level, "subset": sname,
                          "mechanism": mname})
                rows.append(r)
    return rows


def city_slopes(d, outcome, mech):
    rows = []
    for c, g in d.groupby("processing_acps"):
        if g[mech].std() < 1e-14:
            continue
        fit = smf.ols(f"{outcome} ~ {mech}", data=g).fit()
        x = g[mech]
        rows.append({"city": c, "beta": fit.params[mech], "p": fit.pvalues[mech],
                     "n": int(fit.nobs), "within_var": float(((x - x.mean()) ** 2).sum())})
    r = pd.DataFrame(rows)
    r["weight"] = r["within_var"] / r["within_var"].sum()
    r["contribution"] = r["beta"] * r["weight"]
    return r.sort_values("weight", ascending=False)


def mean_group(cs):
    b = cs["beta"].values
    mg, se = b.mean(), b.std(ddof=1) / np.sqrt(len(b))
    t = mg / se
    return {"mean_group": mg, "se": se, "t": t,
            "p": 2 * (1 - sps.t.cdf(abs(t), len(b) - 1)), "k_cities": len(b)}


def poolability(d, outcome, mech):
    r = smf.ols(f"{outcome} ~ {mech} + C(processing_acps)", data=d).fit()
    u = smf.ols(f"{outcome} ~ {mech}*C(processing_acps)", data=d).fit()
    dfn = u.df_model - r.df_model
    F = ((r.ssr - u.ssr) / dfn) / (u.ssr / u.df_resid)
    return {"F": F, "df_num": dfn, "df_den": u.df_resid,
            "p": 1 - sps.f.cdf(F, dfn, u.df_resid)}


def clustered(d, outcome, mech):
    fit = smf.ols(f"{outcome} ~ {mech} + C(processing_acps)", data=d).fit(
        cov_type="cluster", cov_kwds={"groups": d["processing_acps"]})
    return {"beta": fit.params[mech], "se": fit.bse[mech], "p": fit.pvalues[mech]}


# ---------------------------------------------------------------------------
# Levels
# ---------------------------------------------------------------------------
def validation_levels(df):
    d = compute_derived_monthly_indicators(df)
    d = d[(d["month"] >= EVAL_START) & (d["month"] <= EVAL_END)]
    per_run = d.groupby(["processing_acps", "run_id"])[INDICATORS].mean().reset_index()
    return per_run[INDICATORS].mean(), per_run.groupby("processing_acps")[INDICATORS].mean()


def paper_table2(df):
    d = compute_derived_monthly_indicators(df)
    d = d[(d["month"] >= EVAL_START) & (d["month"] <= EVAL_END)]
    pr = d.groupby("run_id")[list(PAPER_TABLE2)].mean()
    return pd.DataFrame({"median": pr.median(), "p10": pr.quantile(.1),
                         "p90": pr.quantile(.9)})



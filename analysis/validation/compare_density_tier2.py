def stars(p):
    return "***" if p < 0.01 else "**" if p < 0.05 else "*" if p < 0.1 else ""


def assign_seed(df):
    """Give every run a seed index that is unique *and* matched within a city.

    The replication index in `simulation_id` restarts at 0 in every launch, and
    RIO DE JANEIRO was run as two separate `-n 5` launches (2026-08-05 and
    2026-08-07) whose seed-0 runs are demonstrably different draws. Keying on
    the bare index would treat those as one seed and cross-join the two blocks.
    The launch timestamp is therefore part of the key; within a city the
    (timestamp, index) blocks are renumbered 0..k-1 so that `seed < 3` still
    means "the first three replications".
    """
    ts = df["simulation_id"].str.split("__").str[0]
    idx = df["simulation_id"].str.split("__").str[-1].astype(int)
    key = ts + "#" + idx.astype(str)
    order = (pd.DataFrame({"city": df["processing_acps"], "key": key})
             .drop_duplicates().sort_values(["city", "key"]))
    order["seed"] = order.groupby("city").cumcount()
    m = dict(zip(zip(order["city"], order["key"]), order["seed"]))
    return pd.Series(list(map(m.get, zip(df["processing_acps"], key))), index=df.index)



# Delta panels -- the logic of papers/density_housing_inequality/prepare_data.py
# ---------------------------------------------------------------------------
def build_panels(stats, reg):
    T = stats["month"].max()
    T0 = T - pd.DateOffset(months=WINDOW_MONTHS - 1)
    sw = stats[(stats["month"] >= T0) & (stats["month"] <= T)]
    rw = reg[(reg["month"] >= T0) & (reg["month"] <= T)]

    gacp = ["simulation_id", "processing_acps", "interest_housing",
            "policy_melhorias", "seed"]
    gmun = ["simulation_id", "processing_acps", "mun_id", "interest_housing",
            "policy_melhorias", "seed"]
    sm = sw.groupby(gacp)[ACP_COLS].mean().reset_index()
    rm = rw.groupby(gmun)[MUN_COLS].mean().reset_index()

    base_a = (sm["policy_melhorias"] == BASELINE_PM) & (sm["interest_housing"] == BASELINE_IH)
    base_r = (rm["policy_melhorias"] == BASELINE_PM) & (rm["interest_housing"] == BASELINE_IH)

    ba = (sm[base_a][["processing_acps", "seed"] + ACP_COLS]
          .rename(columns={c: f"{c}_base" for c in ACP_COLS}))
    br = (rm[base_r][["processing_acps", "mun_id", "seed"] + MUN_COLS]
          .rename(columns={c: f"{c}_base" for c in MUN_COLS}))

    acp = sm[~base_a].merge(ba, on=["processing_acps", "seed"], how="inner")
    mun = rm[~base_r].merge(br, on=["processing_acps", "mun_id", "seed"], how="inner")

    for c in ["gini_index", "house_price", "affordability_median",
              "house_quality", "house_vacancy", "unemployment"]:
        acp[f"delta_{c}"] = acp[c] - acp[f"{c}_base"]
    acp = acp.rename(columns={"delta_gini_index": "delta_gini",
                              "delta_house_vacancy": "delta_vacancy"})
    for c in ["regional_gini", "regional_house_values", "median_affordability"]:
        mun[f"delta_{c}"] = mun[c] - mun[f"{c}_base"]

    label = lambda r: f"{r['interest_housing']}_{'active' if r['policy_melhorias'] else 'inactive'}"
    acp["policy_config"] = acp.apply(label, axis=1)
    mun["policy_config"] = mun.apply(label, axis=1)

    # Capital = largest municipality by baseline window-mean population.
    cap_pop = br.groupby(["processing_acps", "mun_id"])["pop_base"].mean().reset_index()
    caps = (cap_pop.loc[cap_pop.groupby("processing_acps")["pop_base"].idxmax(),
                        ["processing_acps", "mun_id"]]
            .rename(columns={"mun_id": "capital_mun_id"}))
    mun = mun.merge(caps, on="processing_acps", how="left")
    mun["is_capital"] = mun["mun_id"] == mun["capital_mun_id"]

    cap = mun[mun["is_capital"]].copy()

    per = mun[~mun["is_capital"]].copy()
    for src, dst in [("delta_regional_gini", "w_g"),
                     ("delta_regional_house_values", "w_h"),
                     ("delta_median_affordability", "w_a")]:
        per[dst] = per[src] * per["pop_base"]
    gp = ["processing_acps", "policy_config", "interest_housing",
          "policy_melhorias", "seed"]
    pa = per.groupby(gp).agg(sg=("w_g", "sum"), sh=("w_h", "sum"), sa=("w_a", "sum"),
                             total_pop=("pop_base", "sum"),
                             n_municipalities=("mun_id", "nunique")).reset_index()
    pa["delta_gini_periphery"] = pa["sg"] / pa["total_pop"]
    pa["delta_house_values_periphery"] = pa["sh"] / pa["total_pop"]
    pa["delta_median_affordability_periphery"] = pa["sa"] / pa["total_pop"]
    per_out = pa.drop(columns=["sg", "sh", "sa"])
    return acp, cap, per_out, (T0, T)


def load_published_panels(cities=None):
    acp = pd.read_csv(PUB_DIR / "acp_deltas.csv")
    cap = pd.read_csv(PUB_DIR / "capital_deltas.csv")
    per = pd.read_csv(PUB_DIR / "periphery_deltas.csv")
    for f in (acp, cap, per):
        f["policy_melhorias"] = f["policy_melhorias"].astype(bool)
    if cities is not None:
        acp = acp[acp["processing_acps"].isin(cities)]
        cap = cap[cap["processing_acps"].isin(cities)]
        per = per[per["processing_acps"].isin(cities)]
    return acp.copy(), cap.copy(), per.copy()



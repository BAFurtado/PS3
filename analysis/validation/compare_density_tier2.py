def load_stats(paths, label):
    df = pd.concat([pd.read_csv(p, low_memory=False) for p in np.atleast_1d(paths)],
                   ignore_index=True)
    df["month"] = pd.to_datetime(df["month"])
    df["interest_housing"] = df["interest_housing"].map(IH_MAP)
    df["seed"] = assign_seed(df)
    df["policy_melhorias"] = df["policy_melhorias"].astype(bool)
    n = df.groupby("simulation_id")["month"].nunique()
    keep = n[n == COMPLETE_MONTHS].index
    if len(keep) < len(n):
        bad = n[n < COMPLETE_MONTHS]
        print(f"  [{label}] dropping {len(bad)} incomplete sims "
              f"({sorted(bad.unique())} months)")
        drop_meta = (df[df["simulation_id"].isin(bad.index)]
                     [["processing_acps", "interest_housing", "policy_melhorias"]]
                     .drop_duplicates())
        print(drop_meta.to_string(index=False))
    df = df[df["simulation_id"].isin(keep)].copy()
    df["run_id"] = df["simulation_id"]
    return df


def load_regional(paths, label):
    frames = []
    for p in np.atleast_1d(paths):
        cols = pd.read_csv(p, nrows=0).columns
        frames.append(pd.read_csv(p, usecols=[c for c in REG_USECOLS if c in cols],
                                  low_memory=False))
    df = pd.concat(frames, ignore_index=True)
    df["month"] = pd.to_datetime(df["month"])
    df["interest_housing"] = df["interest_housing"].map(IH_MAP)
    df["seed"] = assign_seed(df)
    df["policy_melhorias"] = df["policy_melhorias"].astype(bool)
    n = df.groupby("simulation_id")["month"].nunique()
    keep = n[n == COMPLETE_MONTHS].index
    if len(keep) < len(n):
        print(f"  [{label}] dropping {len(n) - len(keep)} incomplete regional sims")
    return df[df["simulation_id"].isin(keep)].copy()


